const taskHits = new Map();

function wrapStorageValue(value) {
  return JSON.stringify({
    data: value,
    timestamp: Date.now(),
  });
}

function ok(data) {
  return {
    code: 0,
    data,
  };
}

function jsonResponse(data, status = 200) {
  return {
    status,
    contentType: 'application/json',
    body: JSON.stringify(data),
  };
}

function notFound() {
  return jsonResponse({ code: 404, message: 'not found' }, 404);
}

function getEntryModeFromBody(body) {
  if (!body) {
    return 'create';
  }

  try {
    const parsed = JSON.parse(body);
    return parsed.entryMode || 'create';
  } catch {
    return 'create';
  }
}

function buildSession(entryMode, body = '') {
  let parsed = {};
  try {
    parsed = body ? JSON.parse(body) : {};
  } catch {
    parsed = {};
  }

  const prompt = parsed.prompt || parsed.content || 'Make a small game';
  const sourceGameId = parsed.sourceGameId || '';
  const sessionId = `session-${entryMode}-${Date.now()}`;

  return {
    id: sessionId,
    sessionId,
    status: 'ready',
    entryMode,
    prompt,
    initialPrompt: prompt,
    expandedPrompt:
      entryMode === 'iterate'
        ? 'Keep the core gameplay and make the pacing faster with clearer feedback.'
        : entryMode === 'fork'
          ? 'Keep the core loop, change theme and improve onboarding clarity.'
          : 'Player moves left and right, catches falling coins, and loses score when coins are missed.',
    titleDraft:
      entryMode === 'iterate'
        ? `${SOURCE_GAME.title} 优化版`
        : entryMode === 'fork'
          ? `${SOURCE_GAME.title} Remix`
          : '接金币挑战',
    orientation: 'portrait',
    generationTier: 'standard',
    sourceGameId,
    revision: 1,
    readyToGenerate: true,
    questionBudget: 1,
    currentQuestion: null,
    planDraft: {
      summary: 'A concise plan prepared by mocked backend.',
    },
    confidenceSummary: {
      confidence: 0.92,
    },
    messages: [
      {
        id: `${sessionId}-assistant`,
        role: 'assistant',
        content: '我已经整理好方向，可以直接开始生成。',
        kind: 'summary',
        createdAt: new Date().toISOString(),
      },
    ],
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}

