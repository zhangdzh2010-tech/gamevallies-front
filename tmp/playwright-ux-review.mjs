async function routeApi(route) {
  const request = route.request();
  const url = new URL(request.url());
  const pathname = url.pathname;
  const method = request.method();

  if (pathname.includes('/users/quota')) {
    return route.fulfill(jsonResponse(ok({
      freeQuota: 5,
      totalFreeQuota: 5,
      usedFreeQuota: 0,
      subscription: null,
    })));
  }

  if (pathname.endsWith('/games/creation-sessions/active')) {
    return route.fulfill(notFound());
  }

  if (method === 'POST' && pathname.endsWith('/games/creation-sessions')) {
    const body = request.postData() || '';
    const entryMode = getEntryModeFromBody(body);
    return route.fulfill(jsonResponse(ok(buildSession(entryMode, body))));
  }

  if (method === 'POST' && /\/games\/creation-sessions\/[^/]+\/messages$/.test(pathname)) {
    return route.fulfill(jsonResponse(ok({
      ...buildSession('create', request.postData() || ''),
      revision: 2,
    })));
  }

  if (method === 'POST' && /\/games\/creation-sessions\/[^/]+\/skip$/.test(pathname)) {
    const sessionId = pathname.split('/').at(-2);
    return route.fulfill(jsonResponse(ok({
      ...buildSession('create'),
      id: sessionId,
      sessionId,
      status: 'ready',
      revision: 2,
    })));
  }

  if (method === 'POST' && /\/games\/creation-sessions\/[^/]+\/generate$/.test(pathname)) {
    const sessionId = pathname.split('/').at(-2);
    const entryMode = sessionId.includes('iterate') ? 'iterate' : sessionId.includes('fork') ? 'fork' : 'create';
    const gameId = `generated-${entryMode}-game`;
    const taskId = `task-${entryMode}`;
    createdGames.set(gameId, buildGeneratedGame(entryMode, gameId));
    taskHits.set(taskId, 0);
    return route.fulfill(jsonResponse(ok({
      id: sessionId,
      sessionId,
      status: 'generating',
      entryMode,
      generatedGameId: gameId,
      gameId,
      generationTaskId: taskId,
      titleDraft: createdGames.get(gameId).title,
      initialPrompt: 'mock prompt',
      prompt: 'mock prompt',
      revision: 2,
    })));
  }

  if (method === 'POST' && /\/games\/creation-sessions\/[^/]+\/abandon$/.test(pathname)) {
    return route.fulfill(jsonResponse(ok({ status: 'abandoned' })));
  }

  if (/\/games\/tasks\/[^/]+\/events$/.test(pathname)) {
    const taskId = pathname.split('/').at(-2);
    return route.fulfill(jsonResponse(ok(buildTaskEvents(taskId))));
  }

  if (/\/games\/tasks\/[^/]+\/cancel$/.test(pathname)) {
    const taskId = pathname.split('/').at(-2);
    return route.fulfill(jsonResponse(ok(buildTask(taskId, 'create', 'generated-create-game', 'canceled'))));
  }

  if (/\/games\/tasks\/[^/]+$/.test(pathname)) {
    const taskId = pathname.split('/').at(-1);
    const currentHits = taskHits.get(taskId) || 0;
    taskHits.set(taskId, currentHits + 1);
    const entryMode = taskId.includes('iterate') ? 'iterate' : taskId.includes('fork') ? 'fork' : 'create';
    const gameId = `generated-${entryMode}-game`;
    return route.fulfill(jsonResponse(ok(buildTask(
      taskId,
      entryMode,
      gameId,
      currentHits >= 1 ? 'succeeded' : 'running',
    ))));
  }

  if (/\/games\/[^/]+$/.test(pathname)) {
    const gameId = pathname.split('/').at(-1);
    return route.fulfill(jsonResponse(ok(createdGames.get(gameId) || SOURCE_GAME)));
  }

  if (pathname.includes('/games/my')) {
    return route.fulfill(jsonResponse(ok({
      items: [SOURCE_GAME, ...createdGames.values()],
      total: 1 + createdGames.size,
      page: 1,
      limit: 20,
    })));
  }

  if (pathname.includes('/game-types')) {
    return route.fulfill(jsonResponse(ok([])));
  }

  return route.fulfill(jsonResponse(ok({})));
}

async function createContext(browser) {
  const context = await browser.newContext({
    viewport: { width: 430, height: 932 },
    userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Mobile/15E148',
  });

  await context.addInitScript(({ token, user }) => {
    localStorage.clear();
    localStorage.setItem('gamevallies_access_token', token);
    localStorage.setItem('gamevallies_user', user);
  }, {
    token: wrapStorageValue('mock-token'),
    user: wrapStorageValue(TEST_USER),
  });

  await context.route('**/api/v1/**', routeApi);
  await context.route('**/api/v1/games/creation-sessions/*/events**', async (route) => {
    await route.fulfill({
      status: 200,
      headers: {
        'content-type': 'text/event-stream',
      },
      body: '',
    });
  });

  return context;
}

async function snapshot(page, name, notes = {}) {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const screenshotPath = path.join(OUT_DIR, `${name}.png`);
  await page.screenshot({ path: screenshotPath, fullPage: true });

  const bodyText = await page.locator('body').innerText().catch(() => '');
  const actions = await page.locator(
    '.creation-create-composer__action, .creation-session-actions__button, .creation-result-cover-card__action'
  ).evaluateAll((elements) => elements.map((element) => {
    const rect = element.getBoundingClientRect();
    return {
      text: element.innerText,
      className: element.className,
      rect: {
        top: Math.round(rect.top),
        bottom: Math.round(rect.bottom),
        height: Math.round(rect.height),
      },
      fullyInViewport: rect.top >= 0 && rect.bottom <= window.innerHeight,
    };
  })).catch(() => []);

  const layout = await page.evaluate(() => ({
    url: location.href,
    viewportWidth: window.innerWidth,
    bodyScrollWidth: document.body.scrollWidth,
    documentScrollWidth: document.documentElement.scrollWidth,
    hasHorizontalOverflow:
      Math.max(document.body.scrollWidth, document.documentElement.scrollWidth) > window.innerWidth + 2,
  }));

  return {
    name,
    screenshotPath,
    url: page.url(),
    bodyText,
    actions,
    layout,
    ...notes,
  };
}

async function clickActionByText(page, text) {
  const action = page.locator(
    '.creation-create-composer__action, .creation-session-actions__button, .creation-result-cover-card__action'
  ).filter({ hasText: text }).first();
  await action.scrollIntoViewIfNeeded();
  await action.click();
}

async function runFlow(browser, flow) {
  const context = await createContext(browser);
  const page = await context.newPage();
  const consoleErrors = [];
  const requestFailures = [];

  page.on('console', (msg) => {
    if (msg.type() === 'error') {
      const text = msg.text();
      if (!/creation-sessions\/active|404 \(Not Found\)/i.test(text)) {
        consoleErrors.push(text);
      }
    }
  });
  page.on('requestfailed', (request) => {
    requestFailures.push(`${request.method()} ${request.url()} ${request.failure()?.errorText || ''}`);
  });

  const pageUrl =
    flow === 'create'
      ? `${BASE_URL}/#/pages/create/index`
      : flow === 'iterate'
        ? `${BASE_URL}/#/pages/game/iterate/index?gameId=${SOURCE_GAME.id}`
        : `${BASE_URL}/#/pages/game/fork/index?sourceGameId=${SOURCE_GAME.id}`;

  const inputText =
    flow === 'create'
      ? '做一个接金币小游戏，玩家左右移动接金币，漏接扣分'
      : flow === 'iterate'
        ? '让节奏更快，命中反馈更明显，难度曲线更顺滑'
        : '保留跳跃收集核心，把题材换成像素太空探险';

  try {
    await page.goto(pageUrl, { waitUntil: 'domcontentloaded', timeout: 60000 });
    await page.locator('.creation-create-editor__input--native').first().waitFor({ state: 'visible', timeout: 20000 });
    await page.locator('.creation-create-editor__input--native').first().fill(inputText);
    await page.waitForTimeout(300);
    const initial = await snapshot(page, `${flow}-01-entry`);

    await page.locator('.creation-create-composer__action--primary').first().click();
    await page.waitForTimeout(1200);
    const prepared = await snapshot(page, `${flow}-02-prepared`);

    await clickActionByText(page, '开始生成');
    await page.waitForTimeout(1500);
    const progress = await snapshot(page, `${flow}-03-progress`);

    await page.waitForTimeout(9200);
    const result = await snapshot(page, `${flow}-04-result`);

    await context.close();
    return {
      flow,
      ok: true,
      consoleErrors,
      requestFailures,
      snapshots: [initial, prepared, progress, result],
    };
  } catch (error) {
    const failureSnapshot = await snapshot(page, `${flow}-failure`, {
      error: String(error?.message || error),
    }).catch(() => null);
    await context.close().catch(() => {});
    return {
      flow,
      ok: false,
      error: String(error?.stack || error?.message || error),
      consoleErrors,
      requestFailures,
      snapshots: failureSnapshot ? [failureSnapshot] : [],
    };
  }
}

async function runDirectFlow(browser, flow) {
  const context = await createContext(browser);
  const page = await context.newPage();
  const pageUrl =
    flow === 'create'
      ? `${BASE_URL}/#/pages/create/index`
      : flow === 'iterate'
        ? `${BASE_URL}/#/pages/game/iterate/index?gameId=${SOURCE_GAME.id}`
        : `${BASE_URL}/#/pages/game/fork/index?sourceGameId=${SOURCE_GAME.id}`;
  const inputText =
    flow === 'create'
      ? '直接生成一个躲避陨石小游戏'
      : flow === 'iterate'
        ? '直接把手感调快一点'
        : '直接复刻成太空主题';

  try {
    await page.goto(pageUrl, { waitUntil: 'domcontentloaded', timeout: 60000 });
    await page.locator('.creation-create-editor__input--native').first().waitFor({ state: 'visible', timeout: 20000 });
    await page.locator('.creation-create-editor__input--native').first().fill(inputText);
    await page.waitForTimeout(300);
    await clickActionByText(page, '直接生成');
    await page.waitForTimeout(1600);
    const progress = await snapshot(page, `${flow}-direct-progress`);
    await context.close();
    return {
      flow,
      ok: /AI 正在|AI 创作|AI 优化|AI 复刻|正在理解/.test(progress.bodyText),
      snapshot: progress,
    };
  } catch (error) {
    const failureSnapshot = await snapshot(page, `${flow}-direct-failure`, {
      error: String(error?.message || error),
    }).catch(() => null);
    await context.close().catch(() => {});
    return {
      flow,
      ok: false,
      error: String(error?.stack || error?.message || error),
      snapshot: failureSnapshot,
    };
  }
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const flows = [];
  const directFlows = [];

  try {
    for (const flow of ['create', 'iterate', 'fork']) {
      flows.push(await runFlow(browser, flow));
    }

    for (const flow of ['create', 'iterate', 'fork']) {
      directFlows.push(await runDirectFlow(browser, flow));
    }
  } finally {
    await browser.close();
  }

  const report = {
    baseUrl: BASE_URL,
    generatedAt: new Date().toISOString(),
    flows,
    directFlows,
  };
  const reportPath = path.join(OUT_DIR, 'report.json');
  await fs.writeFile(reportPath, JSON.stringify(report, null, 2), 'utf8');
  console.log(JSON.stringify({
    reportPath,
    ok: flows.every((flow) => flow.ok),
    flows: flows.map((flow) => ({
      flow: flow.flow,
      ok: flow.ok,
      snapshots: flow.snapshots.map((snapshotItem) => ({
        name: snapshotItem.name,
        screenshotPath: snapshotItem.screenshotPath,
        hasHorizontalOverflow: snapshotItem.layout?.hasHorizontalOverflow,
        actions: snapshotItem.actions.map((action) => ({
          text: action.text,
          fullyInViewport: action.fullyInViewport,
          rect: action.rect,
        })),
      })),
      consoleErrors: flow.consoleErrors,
      requestFailures: flow.requestFailures,
      error: flow.error,
    })),
    directFlows: directFlows.map((flow) => ({
      flow: flow.flow,
      ok: flow.ok,
      screenshotPath: flow.snapshot?.screenshotPath,
      hasHorizontalOverflow: flow.snapshot?.layout?.hasHorizontalOverflow,
      actions: flow.snapshot?.actions?.map((action) => ({
        text: action.text,
        fullyInViewport: action.fullyInViewport,
        rect: action.rect,
      })),
      error: flow.error,
    })),
  }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
